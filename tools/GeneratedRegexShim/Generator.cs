using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace GeneratedRegexShim;

[Generator]
public sealed class Generator : IIncrementalGenerator
{
	private const string AttributeName = "Mermaider.Compat.GeneratedRegexAttribute";

	private const string AttributeSource =
		"""
		namespace Mermaider.Compat
		{
			[global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false)]
			internal sealed class GeneratedRegexAttribute : global::System.Attribute
			{
				public GeneratedRegexAttribute(string pattern) { }
				public GeneratedRegexAttribute(string pattern, global::System.Text.RegularExpressions.RegexOptions options) { }
				public GeneratedRegexAttribute(string pattern, global::System.Text.RegularExpressions.RegexOptions options, int matchTimeoutMilliseconds) { }
			}
		}
		""";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(c => c.AddSource("GeneratedRegexAttribute.g.cs", AttributeSource));

		var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
			AttributeName,
			static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.MethodDeclarationSyntax,
			static (ctx, _) => Describe(ctx)
		);

		context.RegisterSourceOutput(methods.Collect(), static (spc, all) =>
		{
			foreach (var group in all.Where(m => m is not null).GroupBy(m => m!.TypeKey))
			{
				var first = group.First()!;
				var sb = new StringBuilder();
				sb.AppendLine("// <auto-generated/>");
				sb.AppendLine("#nullable enable");
				sb.AppendLine("using System;");
				sb.AppendLine("using System.Text.RegularExpressions;");
				if (first.Namespace.Length > 0)
					sb.Append("namespace ").Append(first.Namespace).AppendLine(" {");
				foreach (var open in first.TypeOpeners)
					sb.AppendLine(open);
				foreach (var m in group)
				{
					// lazy, not a static initializer: initializer order across partial declarations is unspecified, and other
					// static fields of the type may call the method while they initialize
					sb.Append("\tprivate static Regex? __").Append(m!.Name).AppendLine(";");
					sb
						.Append('\t')
						.Append(m.Accessibility)
						.Append(" static partial Regex ")
						.Append(m.Name)
						.Append("() => __")
						.Append(m.Name)
						.Append(" ??= new Regex(")
						.Append(m.Pattern)
						.Append(", (RegexOptions)")
						.Append(m.Options)
						.Append(", TimeSpan.FromMilliseconds(")
						.Append(m.TimeoutMs)
						.AppendLine("));");
				}
				for (var i = 0; i < first.TypeOpeners.Length; i++)
					sb.AppendLine("}");
				if (first.Namespace.Length > 0)
					sb.AppendLine("}");
				spc.AddSource(new string(first.TypeKey.Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray()) + ".Regex.g.cs", sb.ToString());
			}
		});
	}

	private static Method? Describe(GeneratorAttributeSyntaxContext ctx)
	{
		if (ctx.TargetSymbol is not IMethodSymbol method || ctx.Attributes.Length == 0)
			return null;
		var args = ctx.Attributes[0].ConstructorArguments;
		if (args.Length == 0 || args[0].Value is not string pattern)
			return null;
		var options = args.Length > 1 ? Convert.ToInt32(args[1].Value) : 0;
		var timeout = args.Length > 2 ? Convert.ToInt32(args[2].Value) : -1;

		var openers = new List<string>();
		for (var t = method.ContainingType; t is not null; t = t.ContainingType)
		{
			var kind = (t.TypeKind == TypeKind.Struct ? "struct" : "class");
			if (t.IsRecord)
				kind = t.TypeKind == TypeKind.Struct ? "record struct" : "record";
			var acc = t.DeclaredAccessibility switch
			{
				Accessibility.Public => "public ",
				Accessibility.Internal => "internal ",
				Accessibility.Private => "private ",
				_ => "",
			};
			openers.Insert(0, $"{acc}{(t.IsStatic ? "static " : "")}partial {kind} {t.Name} {{");
		}
		var acc2 = method.DeclaredAccessibility switch
		{
			Accessibility.Public => "public",
			Accessibility.Internal => "internal",
			Accessibility.Protected => "protected",
			_ => "private",
		};
		var ns = method.ContainingNamespace.IsGlobalNamespace ? "" : method.ContainingNamespace.ToDisplayString();
		return new Method(
			ns + "|" + method.ContainingType.ToDisplayString(),
			ns,
			[.. openers],
			method.Name,
			acc2,
			SymbolDisplay.FormatLiteral(pattern, quote: true),
			options,
			timeout
		);
	}

	private sealed record Method(
		string TypeKey,
		string Namespace,
		string[] TypeOpeners,
		string Name,
		string Accessibility,
		string Pattern,
		int Options,
		int TimeoutMs
	);
}
